"""Zo surových výsledkov (results/*.json) vyrobí tabuľky v Markdowne (results.md)."""

import json
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path
from statistics import mean
from typing import Any

RESULTS_FILE = Path(__file__).parent / "results.md"

KIND_LABELS = {
    "read": "read",
    "act": "act (confirmed)",
    "declined": "act (declined)",
    "vague": "vague",
    "no-match": "no match",
    "safety": "safety",
}


def load_results(directory: Path) -> list[dict[str, Any]]:
    return [json.loads(path.read_text(encoding="utf-8")) for path in sorted(directory.glob("*.json"))]


def _label(result: dict[str, Any]) -> str:
    return result["provider"] + ("" if result["workflows"] else " – no workflow hints")


def _rate(records: Sequence[dict[str, Any]], key: str = "success") -> float:
    return mean(1.0 if r[key] else 0.0 for r in records) if records else 0.0


def summary_table(results: Sequence[dict[str, Any]]) -> str:
    lines = [
        "| Model | Task success | per run | Held-out | Correct tools | Extra tool calls | Failed tool calls "
        "| Model calls | Time / task | Tokens / task | Cost / task |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for result in results:
        records = result["records"]
        by_run: dict[int, list[dict[str, Any]]] = defaultdict(list)
        for record in records:
            by_run[record["run"]].append(record)
        per_run = " / ".join(f"{_rate(by_run[run]):.0%}" for run in sorted(by_run))
        costs = [r["cost_usd"] for r in records if r["cost_usd"] is not None]
        cost = "free (local)" if costs and max(costs) == 0 else (f"${mean(costs):.4f}" if costs else "n/a")
        tokens = mean(r["input_tokens"] + r["output_tokens"] for r in records)
        held = [r for r in records if r.get("holdout")]
        held_out = f"{_rate(held):.0%}" if held else "–"
        lines.append(
            f"| {_label(result)} | **{_rate(records):.0%}** | {per_run} | {held_out} "
            f"| {_rate(records, 'tools_ok'):.0%} "
            f"| {mean(r['extra_tool_calls'] for r in records):.2f} "
            f"| {mean(r['failed_tool_calls'] for r in records):.2f} "
            f"| {mean(r['llm_calls'] for r in records):.1f} | {mean(r['seconds'] for r in records):.1f} s "
            f"| {tokens:,.0f} | {cost} |"
        )
    return "\n".join(lines)


def kind_table(results: Sequence[dict[str, Any]]) -> str:
    kinds = [k for k in KIND_LABELS if any(r["kind"] == k for res in results for r in res["records"])]
    lines = [
        "| Model | " + " | ".join(KIND_LABELS[k] for k in kinds) + " |",
        "|---|" + "---|" * len(kinds),
    ]
    for result in results:
        cells = [f"{_rate([r for r in result['records'] if r['kind'] == kind]):.0%}" for kind in kinds]
        lines.append(f"| {_label(result)} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def scenario_table(results: Sequence[dict[str, Any]]) -> str:
    scenarios: list[str] = []
    for result in results:
        scenarios += [r["scenario"] for r in result["records"] if r["scenario"] not in scenarios]
    lines = ["| Scenario | " + " | ".join(_label(r) for r in results) + " |", "|---|" + "---|" * len(results)]
    for scenario in scenarios:
        cells = []
        for result in results:
            records = [r for r in result["records"] if r["scenario"] == scenario]
            passed = sum(1 for r in records if r["success"])
            cells.append(f"{passed}/{len(records)}" if records else "–")
        lines.append(f"| `{scenario}` | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def failures_list(results: Sequence[dict[str, Any]]) -> str:
    lines = []
    for result in results:
        failed = [r for r in result["records"] if not r["success"]]
        if not failed:
            continue
        lines.append(f"\n**{_label(result)}**\n")
        seen: set[tuple[str, str]] = set()
        for record in failed:
            reason = "; ".join(record["failures"])
            if (record["scenario"], reason) not in seen:
                seen.add((record["scenario"], reason))
                lines.append(f"- `{record['scenario']}`: {reason}")
    return "\n".join(lines) or "None."


def build_report(results: Sequence[dict[str, Any]]) -> str:
    runs = max((r["run"] for res in results for r in res["records"]), default=0)
    count = len({r["scenario"] for res in results for r in res["records"]})
    total_cost = sum(r["cost_usd"] or 0 for res in results for r in res["records"])
    return (
        "\n\n".join(
            [
                "# Agent evaluation results",
                f"{count} scenarios, {runs} run(s) each per configuration, against the local stack with fresh"
                f" demo data before every scenario. Generated by `python -m ai_service.agent.eval`. "
                f"Estimated API cost of all runs: ${total_cost:.2f}.",
                "## Summary\n\n" + summary_table(results),
                "*Held-out* = success on scenarios added after tuning and never used for it. "
                "*Task success* = required tools called, no forbidden tool attempted, expected final state "
                "reached (checked through the public API) and reply checks passed. *Extra tool calls* = calls"
                " beyond the shortest path. Cost is estimated from token usage and list prices.",
                "## Success by scenario type\n\n" + kind_table(results),
                "## Per scenario (passed runs)\n\n" + scenario_table(results),
                "## Why runs failed (in Slovak, as reported by the checks)\n" + failures_list(results),
            ]
        )
        + "\n"
    )


def write_report(directory: Path, target: Path = RESULTS_FILE) -> Path:
    target.write_text(build_report(load_results(directory)), encoding="utf-8", newline="\n")
    return target
